# -- finite computations -----------------------------------------------------------------------------
def weil_moduli(n: int) -> int:
    """dim of the polarised Weil family D_{n,n}: n^2."""
    return n * n


def schoen_product_dim(n: int) -> int:
    """dim of the products B x B' of Weil varieties of dimensions 2a, 2b with a + b = n (a, b >= 1): max a^2 + b^2."""
    return max(a * a + (n - a) ** 2 for a in range(1, n))


def polarised_rank(n: int, rho: int = 3) -> int:
    """r(ch E) for Hankel rank rho = 3 on a product of two Weil n-folds... the paper's value 7n^2 - 2n."""
    assert rho == 3
    return 7 * n * n - 2 * n


def fermat_shadows(a=(1, 16, 26, 31, 36), m: int = 55) -> List[int]:
    """Non-units t with t a_k != 0 mod m and sum <t a_k> = m: lattice points of the Fine interior (H8 Rem 4.26(b))."""
    return [t for t in range(1, m) if gcd(t, m) > 1 and all((t * x) % m for x in a) and sum((t * x) % m for x in a) == m]


def similarity_field(deg: int, products: List[int]) -> str:
    """prop:structure(v): the algebra generated by correspondences with p_g <= 1 is the multiquadratic field of the
    sqrt(d_1 d_2); when [E:Q] is odd it is Q."""
    if deg % 2:
        return "Q"
    return "Q(" + ", ".join(f"sqrt {d}" for d in sorted({d for d in products if int(math.isqrt(d)) ** 2 != d})) + ")"


FINITE_GROUP_CENTRES = {"cyclic m": "Q(zeta_m)", "dihedral m": "Q(zeta_m)^+", "tetrahedral": "Q(sqrt -3)",
                        "octahedral": "Q", "icosahedral": "Q(sqrt 5)"}


def cubic_fields_from_finite_groups(max_conductor: int = 50) -> List[str]:
    """prop:cubicstop(iii): the only cubic fields among the centres are Q(zeta_7)^+ and Q(zeta_9)^+."""
    out = []
    for m in range(3, max_conductor + 1):
        phi = sum(1 for k in range(1, m + 1) if gcd(k, m) == 1)
        if phi // 2 == 3 and m % 4 != 2:      # [Q(zeta_m)^+ : Q] = phi(m)/2 = 3; Q(zeta_2m) = Q(zeta_m) for odd m
            out.append(f"Q(zeta_{m})^+")
    return out


def abelian_cover_meagre(m: int, n: int, k_chi: int) -> Tuple[int, int]:
    """H8 prop:coversreach: an isotypic part of (F, n)-Weil type on an abelian cover of a curve is pulled back from a
    locus of dimension 3n - k_chi/2 inside a Weil family of dimension m n^2."""
    return 3 * n - k_chi // 2, m * n * n


def link_closes(K_has_imaginary_quadratic: bool) -> bool:
    """thm:link(iv): a(e) notin Q for every e iff K contains no imaginary quadratic field."""
    return not K_has_imaginary_quadratic


# -- the check --------------------------------------------------------------------------------------------
def check_hodge(c: Con) -> Check:
    p = set(c.parts)
    # (F2): the lift from CM points
    if "p.propagation" in p:
        if "p.criterion" in p and "p.product" in p and "h8.markman" in p:
            n = 3
            return Check("stopped", "H.F2.lift", "the product object has the polarised shape and Hankel rank 3, so the "
                         f"criterion asks dim Ext^2 = {polarised_rank(n)} at a CM point; this is the E_0^6 target, "
                         "not yet met", dict(r=polarised_rank(n), needs="ext2-57"))
        if "l.openai032" in p:
            return Check("rejected", "H.F2.lift", "the CM input is an unrefereed preprint with no Lean form",
                         dict(unrefereed=True))
        if "l.fermat110" in p:
            sh = fermat_shadows()
            return Check("stopped", "H.F2.lift", "the CM point is known; the character (1,16,26,31,36) at level 55 has "
                         f"a shadow t in {sh}, so no block family and no uniruled quotient; the object at that point "
                         "is the open step", dict(shadows=sh))
        if "l.ribet" in p or "h8.escape" in p or "h8.covers" in p or "l.shimura" in p:
            if "h8.covers" in p:
                d, D = abelian_cover_meagre(2, 2, 2)
                return Check("rejected", "H.F2.lift", f"abelian covers reach a locus of dimension {d} in a Weil family "
                             f"of dimension {D}: meagre (H8 prop:coversreach)", dict(dim=d, family=D))
            return Check("stopped", "H.F2.lift", "the CM point exists (the family through every Hodge class has a CM "
                         "member); the semiregular object at it is the open step", dict(needs="semiregular-object"))
        if "l.bbf" in p or "l.pridham" in p or "p.criterion" in p:
            return Check("stopped", "H.F2.lift", "semiregularity lifts a class only from an object whose Chern "
                         "character is the class and whose semiregularity map is injective; no such object is known at "
                         "any CM point for a Weil class in dimension >= 6 or a Mumford exceptional class")
        return Check("stopped", "H.F2.lift", "no check for this composite of the propagation theorem")
    if "p.andreoort" in p:
        return Check("rejected", "H.F2.lift", "Andre-Oort replaces the dense orbit by one sequence of CM points; the "
                     "lift at those points is the same open step (H8 thm:escape: still an equivalence)")
    if "p.surgery" in p:
        return Check("rejected", "H.F2", "blow-ups, finite covers, birational models and derived equivalences carry "
                     "the degree-four defect unchanged (prop:surgery (i)-(iii)); degenerations return the class only "
                     "through (V) (prop:surgery (iv))", dict(defect_change=0))
    if "l.degeneration" in p or "l.fm" in p:
        return Check("rejected", "H.F2", "a degeneration to E^n or a Fourier-Mukai partner moves the class to a model "
                     "where it is algebraic only by losing it or by keeping the defect (prop:surgery (iii), (iv))")
    # (F2): the E_0^6 target
    if "p.convolution3" in p:
        return Check("rejected", "H.F2.E06", f"convolutions with at most three line bundles at E_0^6 have dim Ext^2 > "
                     f"{polarised_rank(3)} (prop:separated); H8 thm:noconvolution gives >= 69 for |t_i - p| >= 2",
                     dict(r=polarised_rank(3), ext2_lower=69))
    if "p.convolution4" in p:
        if "h8.e06" in p or "h8.e08" in p:
            return Check("stopped", "H.F2.E06", "H8 excludes every convolution on E_0^6 with |t_i - p| >= 2 (>= 69 > 57) "
                         "and on E_0^8 within six consecutive shifts (>= 640 > 104); four or more line bundles with "
                         "|t_i - p| <= 1, and pieces meeting along surfaces, have no computed Ext algebra",
                         dict(open="|t_i - p| <= 1 or pieces along surfaces"))
        if "p.cmext" in p:
            return Check("stopped", "H.F2.E06", "lem:cmext gives every Ext group at E_0^6; the rank of the products "
                         "along the closed chains for four or more line bundles is the open computation",
                         dict(needs="rank of fourfold Massey products with >= 4 line bundles"))
        return Check("stopped", "H.F2.E06", "the Ext algebra of the pieces is needed (lem:cmext)")
    if "h8.weiltori" in p and ("p.product" in p or "p.criterion" in p):
        return Check("rejected", "H.F2.E06", "the pure criterion (Chern character exactly a Weil class) is false: the "
                     "very general Weil torus carries no such object (H8 thm:p2false); only the polarised shape remains",
                     dict(pure=False))
    if "h8.quartic" in p:
        return Check("stopped", "H.F2.E06", "at a quartic CM field the rank is at least 80 and never 100; a complex "
                     "meeting the quartic criterion needs non-constant polynomial part and dim Ext^2 >= 88 (H8 "
                     "thm:quarticrank, cor:quarticleast)", dict(rank_min=80))
    if "p.product" in p and "h8.markman" in p:
        return Check("accepted", "H.F2.product", "the product object exists on A x A' when W(A), W(A') are algebraic "
                     "(thm:product, with Markman's fourfolds): Hankel rank 3, r = 7n^2 - 2n", dict(known=True, r=polarised_rank(3)))
    # (F2): the sixfold link
    if "p.link" in p:
        if "p.hk" in p:
            return Check("rejected", "H.F2.link", "hyper-Kaehler carriers give a(e) = +-1 in Q: the link closes nothing "
                         "(prop:hk)")
        if "l.ks" in p:
            return Check("stopped", "H.F2.link", "the Kuga-Satake class in degree 2^7 is the older link (H8 thm 21.4); "
                         "its algebraicity is the Kuga-Satake Hodge conjecture, open")
        if "l.andre" in p or "l.deligne" in p:
            return Check("rejected", "H.F2.link", "xi is absolute Hodge (Deligne) and motivated only if the standard "
                         "conjecture B holds (Andre): circular", dict(circular="B"))
        if "l.murty" in p:
            return Check("stopped", "H.F2.link", "xi lies in a mixed Kuenneth component H^1(X) (x) H^1(X) (x) H^2(Z_K) "
                         "with Hom(X, Z_K) = 0; the generation theorems for CM abelian varieties do not reach it, even "
                         "at the CM points of C (ssec:f2stop2)", dict(known_at_cm_points=False))
        return Check("stopped", "H.F2.link", "the link closes the exceptional classes when K has no imaginary quadratic "
                     f"subfield (closes={link_closes(False)}); the algebraicity of xi itself is the open step")
    # (F3'): the cubic correspondence
    if "p.dihedral" in p:
        fields = cubic_fields_from_finite_groups()
        if "l.nikulin" in p or "p.hecke" in p or "l.vangeemen08" in p:
            return Check("accepted", "H.F3p.zeta79", f"the dihedral families reach exactly the cyclic cubic fields {fields} "
                         "with the algebra D_inf (thm:zeta9, prop:cubicstop(iii)); known in the paper",
                         dict(known=True, fields=fields))
        return Check("stopped", "H.F3p.cubic", f"finite group actions reach only {fields}; conductor >= 13, non-cyclic "
                     "F and the algebras ramified at two finite places are not reached", dict(fields=fields))
    if "p.structure" in p:
        if "l.generaltype" in p:
            return Check("stopped", "H.F3p.cubic", "a correspondence acting on T(S_lambda) by a non-similarity needs an "
                         "irreducible component with p_g >= 2, transcendental rank >= 18, b_2 >= 31, not from a finite "
                         "group when F is not cyclic (prop:structure(iv), prop:hecke(iii)); no construction produces one")
        return Check("rejected", "H.F3p.cubic", "every correspondence with components of p_g <= 1 acts by similarities, "
                     f"whose algebra is {similarity_field(3, [])} for a cubic field (prop:structure(v))",
                     dict(field=similarity_field(3, [])))
    if "l.buskin" in p or "l.mukai" in p or "l.huybrechts" in p:
        if "l.varesco" in p or "l.vgs" in p:
            return Check("accepted", "H.F3p.rmfamilies", "RM by sqrt d on four-dimensional families (Varesco) and the "
                         "seven-dimensional sqrt 5 family (vGS); the eight-dimensional very general member stays open",
                         dict(known=True, covered=7, family=8))
        return Check("rejected", "H.F3p.cubic", "Hodge isometries are algebraic (Buskin, Mukai, Huybrechts), but a "
                     "generator of a cubic field is not an isometry and not a similarity: the self-isometries of T(S) "
                     "are +-1", dict(self_isometries="+-1"))
    if {"l.paranjape", "l.floccari", "l.ilp", "l.shiodainose"} & p:
        return Check("rejected", "H.F3p.cubic", "the proved Kuga-Satake cases need transcendental rank <= 6 (<= 5 for "
                     "Shioda-Inose, Picard 16 for Paranjape); S_lambda has transcendental rank 9 and a totally real, "
                     "not CM, endomorphism field (H8 r33)", dict(rank_T=9))
    # (F3'): the start of a chain for composite discriminants
    if c.gives == "rm-family-start":
        if "p.sqrt6" in p or "p.frickeiso" in p:
            return Check("accepted", "H.F3p.d2367", "RM by sqrt d, d in {2,3,5,6,7}, on the families of thm:sqrt6 and "
                         "thm:fricke; known in the paper", dict(known=True, d=[2, 3, 5, 6, 7]))
        return Check("stopped", "H.F3p.sqrt", "for Q(sqrt 10), Q(sqrt 14) no family is known on which the chain starts: "
                     "a symplectic quotient or an elliptic isogeny with that multiplier is needed (ssec:f3stop)")
    if c.gives == "class-A":
        return Check("accepted", "H.F3p.classA", "the variety lies in the class A, so (F3') holds for it (known)",
                     dict(known=True))
    if "h8.schoen" in p:
        n = 3
        return Check("rejected", "H.F2.weil6", f"Schoen products fill dimension {schoen_product_dim(n)} of the "
                     f"{weil_moduli(n)}-dimensional family of Weil sixfolds: meagre",
                     dict(product_dim=schoen_product_dim(n), moduli_dim=weil_moduli(n)))
    if "l.markmanq114" in p:
        return Check("stopped", "H.F2.weil6", "Markman's Question 11.4 (semiregular sheaves on Weil sixfolds and "
                     "eightfolds) is the open step")
    if "l.brosnan" in p:
        return Check("stopped", "H.F2.weil6", "the nonsplit boundary stays outside every proved case (Brosnan 2026)")
    if "l.mz" in p and "h8.markman" in p:
        return Check("accepted", "H.F2.dim5", "(F2) in dimension <= 5 (Moonen-Zarhin with Markman); known", dict(known=True))
    if "l.openai032" in p:
        return Check("rejected", "H.F2.cm", "unrefereed import, no Lean form", dict(unrefereed=True))
    return Check("stopped", "H", "no check is implemented for this composite")


def refute_hodge(c: Con, r: Check, best) -> Tuple[bool, str]:
    m = r.measurement
    if m.get("unrefereed"):
        return False, "rests on an unrefereed import"
    if m.get("circular"):
        return False, f"circular through {m['circular']}"
    if m.get("known"):
        return True, "known result (no new step)"
    return True, "survives"


REACHED = {"F2.lift": "H.F2.lift.closed", "F2.E06": "H.F2.E06.closed", "F2.link": "H.F2.link.closed",
           "F3.cubic": "H.F3p.cubic.closed", "F3.sqrt": "H.F3p.sqrt.closed"}


class HodgeAgent(TargetAgent):
    """One agent per target point of the paper; the library is the Hodge library above."""

    def __init__(self, target: str, mem: Memory):
        self.target = target
        self.bench = "H"
        self.ttype, self.point, self.place = TARGETS[target]
        self.problem = P
        self.mem = mem
        self.lib = list(LIB)
        self.w = {}
        self.channel, self.target_weight = True, True
        self.dist = distances(self.lib, self.ttype)
        self.history, self.known, self.sub = [], set(), []
        mem.db.execute("CREATE TABLE IF NOT EXISTS channel(round INTEGER, bench TEXT, composite TEXT, items INTEGER, "
                       "prior REAL, bundle TEXT)")

    def reached(self, rec) -> bool:
        return any(v["node"] == REACHED[self.target] for v in rec["survivors"].values())

    def gap(self) -> dict:
        """Distance to the target point, measured from the memory: every checked composite whose output is the
        target type, by outcome; the open step recorded for the target's nodes; and whether any survivor was
        more than a known result."""
        prefix = {"F2.lift": "H.F2.lift", "F2.E06": "H.F2.E06", "F2.link": "H.F2.link", "F3.cubic": "H.F3p.cubic",
                  "F3.sqrt": "H.F3p.sqrt"}[self.target]
        counts = dict(self.mem.db.execute("SELECT outcome, COUNT(*) FROM events WHERE node LIKE ? GROUP BY outcome",
                                          (prefix + "%",)))
        steps = [a for (a,) in self.mem.db.execute("SELECT assumption FROM blocks WHERE step LIKE ?", (prefix + "%",))]
        return dict(target=self.target, type=self.ttype, place=self.place, depth=max(self.dist.values()),
                    checked=counts, open_steps=steps,
                    new_non_known=sum(1 for h in self.history if h.get("new_non_known")),
                    reached=any(h["target_reached"] for h in self.history), closes=False)

def install() -> None:
    """Point the shared attack loop at the Hodge checks."""
    S.check5 = check_hodge
    S.refute5 = refute_hodge
    S.LIB5["H"] = list(LIB)
