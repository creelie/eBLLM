"""The frontier map: each benchmark target split into independent pieces along explicit axes.

A target is diagonalised when its statement is the conjunction of pieces indexed by coordinates
(degree and dimension for a standard conjecture, order and averaging for Chowla, n for Erdos 1183),
so that each piece is proved, claimed or open on its own. Closure is then measured per piece.

Status values:
  lean-here      the statement is proved in Lean and was checked in this repository;
  lean-external  a Lean proof exists in another project and was not rebuilt here;
  proved         proved in the refereed literature, not formalised;
  computed       settled by a finite computation with an independently checked certificate;
  claimed        an unrefereed proof exists;
  conditional    proved under a named open hypothesis;
  open           no proof known.
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Dict, List, Optional

CLOSED = ("lean-here", "lean-external", "proved", "computed")
STATUSES = CLOSED + ("claimed", "conditional", "open")


@dataclass
class Piece:
    id: str
    target: str
    statement: str
    axes: Dict[str, str]
    kind: str  # "analytical" or "computational"
    status: str
    source: str = ""
    lean: Optional[str] = None
    missing: str = ""  # for an open piece: the ingredient no known construction supplies

    def __post_init__(self):
        assert self.status in STATUSES, self.status
        assert self.kind in ("analytical", "computational"), self.kind


@dataclass
class Target:
    id: str
    name: str
    pieces: List[Piece] = field(default_factory=list)
    evidence: List[Piece] = field(default_factory=list)

    def measure(self) -> dict:
        n = len(self.pieces)
        count = {s: sum(p.status == s for p in self.pieces) for s in STATUSES}
        closed = sum(count[s] for s in CLOSED)
        return {"target": self.id, "pieces": n, "counts": count,
                "closed": closed, "closure_pct": round(100.0 * closed / n, 1) if n else 0.0,
                "lean_pct": round(100.0 * count["lean-here"] / n, 1) if n else 0.0,
                "open": [p.id for p in self.pieces if p.status == "open"]}


def _b() -> Target:
    t = Target("B", "Grothendieck's standard conjecture B (Lefschetz type)")
    P = lambda i, *a, **k: t.pieces.append(Piece(i, "B", *a, **k))
    P("B.deg1", "B in degrees i <= 1 for every X", {"degree": "<=1", "class": "all"}, "analytical",
      "proved", source="Lieberman 1968; Kleiman 1968 (Picard and Albanese varieties)")
    P("B.dim2", "B for curves and surfaces", {"dimension": "<=2"}, "analytical", "proved",
      source="Lefschetz (1,1) theorem; Grothendieck 1969")
    P("B.abelian", "B for abelian varieties", {"class": "abelian"}, "analytical", "proved",
      source="Lieberman, Amer. J. Math. 90 (1968)")
    P("B.ops", "B is stable under products and smooth ample divisors, hence holds for complete "
      "intersections and every Fermat variety", {"class": "products, ample divisors"}, "analytical",
      "proved", source="Kleiman, Dix exposes (1968)")
    P("B.3.pg0", "B for threefolds with h^{2,0} = 0", {"dimension": "3", "h20": "0"}, "analytical",
      "proved", source="Lefschetz (1,1): H^2 and H^4 = L H^2 are spanned by algebraic classes")
    P("B.3.kappa", "B for threefolds of Kodaira dimension < 3", {"dimension": "3", "kappa": "<3"},
      "analytical", "proved", source="Tankeev, Izv. Math. 75:5 (2011) 1047-1062")
    P("B.arapura", "B for uniruled threefolds, unirational fourfolds, moduli of bundles on curves and "
      "Hilbert schemes of surfaces", {"class": "motivated by curves"}, "analytical", "proved",
      source="Arapura, Adv. Math. 207 (2006)")
    P("B.k3n", "B for hyper-Kahler varieties of K3^[n] type", {"class": "K3^[n]"}, "analytical",
      "proved", source="Charles-Markman, Compos. Math. 149 (2013)")
    P("B.kum", "B for generalized Kummer type in the dimensions of Foster's theorem (n+1 prime and more)",
      {"class": "Kum_n"}, "analytical", "proved", source="Foster, arXiv:2303.14327")
    P("B.kum4d", "B for generalized Kummer type of dimension 4d", {"class": "Kum_n, 4d"}, "analytical",
      "conditional", source="Foster, arXiv:2512.04114, conditional on a conjecture of Buchweitz-Flenner")
    P("B.og10", "B for the OG10-type varieties of Laza-Sacca-Voisin", {"class": "OG10 (LSV)"},
      "analytical", "proved", source="Ancona-Cavicchi-Laterveer-Sacca, J. London Math. Soc. (2025)")
    P("B.og6", "B for O'Grady's six-dimensional examples (motive generated by an abelian surface)",
      {"class": "OG6"}, "analytical", "proved", source="Floccari 2023, as cited in arXiv:2304.00978")
    P("B.3.gt", "B for threefolds of general type with h^{2,0} > 0", {"dimension": "3", "kappa": "3"},
      "analytical", "open",
      missing="an algebraic cycle on X x X inducing the inverse of L: H^2 -> H^4 on the transcendental "
              "lattice T(X); Lefschetz (1,1) only reaches NS(X), and no operation above produces such X")
    P("B.general", "B for every smooth projective variety", {"class": "all"}, "analytical", "open",
      missing="B(X) is the algebraicity of one Hodge class on X x X (the class of Lambda); it follows "
              "from the Hodge conjecture for X x X, and no unconditional source of these cycles exists")
    return t


def _chowla() -> Target:
    t = Target("Chowla", "Chowla's conjecture for the Liouville function")
    P = lambda i, *a, **k: t.pieces.append(Piece(i, "Chowla", *a, **k))
    P("C.k1", "sum_{n<=x} lambda(n) = o(x)", {"k": "1", "average": "ordinary"}, "analytical", "proved",
      source="prime number theorem (Landau 1899)")
    P("C.k2.log", "two-point Chowla with logarithmic averages", {"k": "2", "average": "log"},
      "analytical", "proved", source="Tao, Forum Math. Pi 4 (2016) e8")
    P("C.k2.logq", "two-point logarithmic Chowla with a (log x)^{-c} saving", {"k": "2", "average": "log"},
      "analytical", "proved",
      source="Helfgott-Radziwill (double-log saving); Pilatte, arXiv:2310.19357 (power of log)")
    P("C.odd.log", "logarithmic Chowla for every odd order k", {"k": "odd", "average": "log"},
      "analytical", "proved", source="Tao-Teravainen, Duke Math. J. 168 (2019); J. Theor. Nombres Bordeaux (2018)")
    P("C.k2.ord", "ordinary two-point Chowla, with a (log X)^{-c} saving on nonproportional affine forms",
      {"k": "2", "average": "ordinary"}, "analytical", "claimed",
      source="OpenAI preprint 007 (24 Sep 2026); Lean closure of 1539 files audited here: no sorry, axiom "
             "or native_decide; final statements identical to the comparator; not rebuilt here",
      lean="math01-openAI lean/OAI/NumberTheory/TwoPointCorrelations/FinalMain.lean:liouville_log_saving")
    P("C.even.log", "logarithmic Chowla for every even order k >= 4", {"k": "even>=4", "average": "log"},
      "analytical", "open",
      missing="local Gowers U^{k-1} uniformity of lambda on almost all intervals of length H -> infinity "
              "(equivalent by Tao 2017); known only for degree 1 at H >= exp((log X)^{2/5+eps}) "
              "(Pilatte, arXiv:2604.26564) and for nilsequences at H = X^theta (Matomaki-Radziwill-Tao-"
              "Teravainen-Ziegler, Ann. Math. 2023); the entropy decrement needs the log weight")
    P("C.k3.ord", "ordinary Chowla for k >= 3", {"k": ">=3", "average": "ordinary"}, "analytical", "open",
      missing="the closed-walk estimate of 007 is for the two-point dilation graph; no k-point graph with "
              "an operator bound is known, and the log-weight methods do not apply")
    P("C.full", "Chowla's conjecture for every k with ordinary averages", {"k": "all", "average": "ordinary"},
      "analytical", "open", missing="all of C.even.log and C.k3.ord")
    return t


def _erdos1183(values: Optional[Dict[int, int]] = None) -> Target:
    """The exact small values are evidence for the shape of f, not pieces of the statement f(n) = O(n),
    so they are kept apart and do not enter the closure percentage."""
    t = Target("E1183", "Erdos problem 1183: f(n) = O(n)?")
    t.evidence = [Piece(f"E.f{n}", "E1183", f"f({n}) = {f}", {"n": str(n)}, "computational", "computed",
                        source="SAT and CEGAR, certified by two independent checkers (experiments/erdos1183)")
                  for n, f in sorted((values or {}).items())]
    t.pieces.append(Piece("E.lin", "E1183", "f(n) = O(n)", {"n": "all"}, "analytical", "open",
                          source="Bhattacharjee-Mandal-Bhattacharya, arXiv:2610.02833v1: 11/20 <= f(n)/n "
                                 "<= (2+o(1)) log_2 n",
                          missing="an upper construction beating the log_2 n factor"))
    return t


ERDOS_1183_VALUES = {n: (n + 2) // 2 for n in range(1, 11)}


def targets() -> Dict[str, Target]:
    out = [_b(), _chowla(), _erdos1183(ERDOS_1183_VALUES)]
    return {t.id: t for t in out}


def report() -> List[dict]:
    return [t.measure() for t in targets().values()]


def dump() -> dict:
    return {k: [asdict(p) for p in t.pieces] for k, t in targets().items()}


if __name__ == "__main__":
    for m in report():
        print(f"{m['target']:7s} pieces {m['pieces']:2d} closed {m['closed']:2d} ({m['closure_pct']}%) "
              f"Lean here {m['lean_pct']}%  open: {', '.join(m['open'])}")
