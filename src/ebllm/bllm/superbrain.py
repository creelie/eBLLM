def check_knowledge(c: Con) -> Optional[Check]:
    ks = [KNOWLEDGE[x] for x in c.parts if x in KNOWLEDGE]
    if not ks:
        return None
    stop = [e for e in ks if e["verdict"] == "stops"]
    if stop:
        e = stop[0]
        return Check("stopped", e["benchmark"], f"{e['source']} ({e['lemma']}): {e['note']}",
                     dict(barrier=e["note"], source=e["source"]))
    return Check("accepted", e_node(ks), "; ".join(f"{e['source']}: {e['lemma']} ({e['note']})" for e in ks),
                 dict(known=True))


def e_node(ks):
    return ks[0]["benchmark"] + ".known"


def check5(c: Con) -> Check:
    p = set(c.parts)
    r = check_knowledge(c)
    if r is not None:
        return r
    if "h.andre" in p:
        return Check("stopped", "H.F2", "motivated cycles are algebraic iff the standard conjecture B holds (Andre 1996): "
                     "the route returns to the B benchmark", dict(barrier="no cycles from Hodge classes", circular="B"))
    if "ym.balabandimock" in p and "ym.crossover" in p:
        return Check("stopped", "YM.lattice", "rigorous blocking controls the effective action only while the running "
                     "coupling is small; at the crossover g^2 = 4/beta_W is about 2 to 4", dict(barrier="order-one coupling"))
    if c.problem in ("yang-mills", "hodge"):
        return BO.check2(c)
    if c.problem == "standard-B":
        if "b.kleiman" in p:
            return Check("accepted", "B.ops", "B for products and smooth ample divisors of the proved classes "
                         "(Kleiman 1968)", dict(known=True))
        if "b.arapura" in p:
            return Check("accepted", "B.arapura", "B for varieties motivated by curves (Arapura 2006)", dict(known=True))
        if "b.hodge" in p:
            return Check("stopped", "B.general", "B(X) follows from the Hodge conjecture for X x X; that is the H "
                         "benchmark, open")
        if "b.kscycle" in p:
            return Check("stopped", "B.3.gt", "a Kuga-Satake correspondence exists only for Hodge structures of K3 "
                         "type, and its algebraicity is the Kuga-Satake Hodge conjecture, open; the transcendental "
                         "H^2 of a threefold of general type is not of that type in general")
        return Check("stopped", "B", "no check for this composite")
    if c.problem == "chowla":
        if "c.entropy" in p and "c.logweight" in p:
            return Check("accepted", "C.odd.log", "logarithmic Chowla for odd k (Tao-Teravainen 2019)", dict(known=True))
        if "c.walk" in p and "c.graph2" in p:
            return Check("accepted", "C.k2.ord", "ordinary two-point Chowla with a log saving (OpenAI 007)",
                         dict(unrefereed=True))
        if "c.kwalk" in p:
            return Check("stopped", "C.k3.ord", "no k-point dilation graph with an operator bound is known for k >= 3")
        if "c.shorten" in p and "c.mrt" in p:
            return Check("stopped", "C.even.log", "Matomaki-Radziwill reach intervals of length H -> infinity for "
                         "degree 0 (mean values) and, with Tao, Chowla averaged over the shifts h <= H; local "
                         "U^{k-1} uniformity for fixed shifts needs nilsequences of degree k-2 at that scale",
                         dict(barrier="parity and short intervals"))
        if "c.shorten" in p:
            return Check("stopped", "C.even.log", "uniformity of lambda against nilsequences is known at H = X^theta "
                         "(MRTTZ) and for degree 1 at H = exp((log X)^{2/5+eps}) (Pilatte); Tao's equivalence needs "
                         "all degrees up to k-2 at H -> infinity arbitrarily slowly")
        return Check("stopped", "Chowla", "no check for this composite")
    if c.problem == "erdos1183":
        if "e.family" in p:
            return Check("stopped", "E.lin", "no composition law is known that keeps the largest monochromatic "
                         "sublattice of a product colouring below a linear bound; the values f(n) = n/2 + O(1) for "
                         "n <= 20 are evidence, not a proof")
        if "e.value" in p and "e.poset" in p:
            if "e.grid" in p and F20["witness"]:
                return Check("rejected", "E.f20", "the grid colouring contradicts f(20) >= 12 (twenty-level "
                             "window, BMB26 v5, Thm 7.6); recheck it", dict(witness=F20["witness"]))
            return Check("accepted", "E.f20", "f(n) exact for n <= 20 (level colourings, the chain bound, "
                         "OpenRefute's odd bound and the twenty-level window of BMB26 v5)",
                         dict(known_here=True, f20="12"))
        return Check("stopped", "E1183", "no check for this composite")
    return Check("stopped", "?", "unknown problem")


def refute5(c: Con, r: Check, best: Dict[str, Fraction]) -> Tuple[bool, str]:
    if r.measurement.get("unrefereed"):
        return False, "rests on an unrefereed import"
    if c.problem in ("yang-mills", "hodge"):
        return BO.refute(c, r, best)
    if r.measurement.get("known"):
        return True, "known result"
    return True, "survives"


