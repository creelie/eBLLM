def _llm():
    """The local open-weight model, if llama_cpp and a GGUF file are installed (EBLLM_MODEL or ~/models)."""
    name = "qwen2.5-0.5b-instruct-q4_k_m.gguf"
    cands = [os.environ.get("EBLLM_MODEL", ""), os.path.expanduser("~/models/" + name), "/home/user/models/" + name]
    path = next((c for c in cands if c and os.path.exists(c)), None)
    if path is None:
        return None
    try:
        from llama_cpp import Llama
    except ImportError:
        return None
    return Llama(model_path=path, n_ctx=2048, n_threads=os.cpu_count() or 4, verbose=False)


class LocalModel:
    """Asks the local model to pick one of the candidate crossings, given the retrieved memory."""

    def __init__(self):
        self.model = _llm()
        self.calls = 0

    def pick(self, options: List[str], notes: List[str]) -> int:
        if self.model is None:
            return 0
        prompt = ("You choose which construction to try next on an open mathematical problem.\n"
                  "Past attempts (from memory):\n" + "\n".join(notes[:6]) + "\nOptions:\n" +
                  "\n".join(f"{i}. {o}" for i, o in enumerate(options)) + "\nAnswer with the number only: ")
        out = self.model(prompt, max_tokens=4, temperature=0.0)
        self.calls += 1
        m = re.search(r"\d+", out["choices"][0]["text"])
        i = int(m.group()) if m else 0
        return i if 0 <= i < len(options) else 0


PROPOSERS = ("typed", "novelty", "uniform", "local-model")


def attack(arm: str, memory: Optional[Memory] = None, weights: Optional[Dict[str, float]] = None,
           generations: int = 8, per_gen: int = 10, seed: int = 0, round_: int = 1, retrieval: bool = True,
           committee: bool = True, llm: Optional[LocalModel] = None, eta: float = 1.0, gamma: float = 0.5,
           eps: float = 0.2, library: Optional[List[Con]] = None,
           prior_fn: Optional[Callable[[Con], float]] = None, known_boost: float = 1.0) -> dict:
    """One round of the whole package on the five libraries.

    arm: 'full' (boosters, memory, retrieval, committee), or 'boosted', 'unboosted', 'random' (the
    controls of boosters.run_boosted, on the five libraries).  memory=None runs without long-term
    memory; retrieval=False keeps the memory (decided composites are skipped) but does not use it to
    steer.  Returns the record of the round."""
    rng = random.Random(seed)
    lib = list(library) if library is not None else [c for v in LIB5.values() for c in v]
    pool: List[Con] = list(lib)
    seen = {c.parts for c in pool}
    w = dict(weights or {})
    made_by: Dict[Tuple[str, ...], Tuple[Con, Con]] = {}
    best = dict(BO.KNOWN_BEST)
    boosted = arm in ("full", "boosted")
    sel = SpikingSelector(names=list(PROPOSERS)) if committee and arm == "full" else None
    rec = dict(arm=arm, seed=seed, round=round_, checks=0, repeats=0, skipped=0, survivors={}, refuted=[],
               first={}, checked_seqs=[], proposers={p: dict(turns=0, survivors=0) for p in PROPOSERS}, retrieved=0, llm_calls=0)
    if memory is not None:
        memory.add_nodes(lib)
    key = lambda a, b: f"{a.parts[0]}|{b.parts[0]}"

    for g in range(1, generations + 1):
        typed = []
        for a in pool:
            for b in pool:
                c = cross(a, b)
                if c and c.parts not in seen:
                    if memory is not None and memory.decided(c.parts):
                        rec["skipped"] += 1
                        continue
                    typed.append((a, b, c))
        if not typed:
            break
        chosen = []
        for _ in range(min(per_gen, len(typed))):
            who = "typed"
            if arm == "random":
                a, b = rng.choice(pool), rng.choice(pool)
                chosen.append((a, b, cross(a, b), "uniform"))
                continue
            if arm == "unboosted":
                i = rng.randrange(len(typed))
            else:
                if sel is not None:
                    order = sel.order(rng)
                    who = PROPOSERS[order[0]]
                    if who == "local-model" and (llm is None or llm.model is None):
                        who = PROPOSERS[order[1]]
                ws = []
                for a, b, c in typed:
                    x = w.get(key(a, b), 1.0) if boosted else 1.0
                    if memory is not None and retrieval and arm == "full":
                        pr, hits = memory.prior(c.parts, k=5, round_=round_, proposer=who, log=False)
                        x *= pr
                    if prior_fn is not None:
                        x *= prior_fn(c)
                    ws.append(x)
                if who == "uniform" or rng.random() < eps:
                    i = rng.randrange(len(typed))
                elif who == "novelty" and memory is not None:
                    nov = [1.0 - max([h["sim"] for h in memory.retrieve(c.parts, k=3, log=False)] or [0.0])
                           for _, _, c in typed]
                    i = max(range(len(typed)), key=lambda j: (nov[j], ws[j], -j))
                elif who == "local-model":
                    top = sorted(range(len(typed)), key=lambda j: -ws[j])[:8]
                    hits = memory.retrieve(typed[top[0]][2].parts, k=6, round_=round_, proposer=who) if memory else []
                    notes = [f"- {h['seq']}: {h['outcome']}; {h['reason'][:80]}" for h in hits]
                    j = llm.pick([typed[t][2].id for t in top], notes)
                    i = top[j]
                    rec["llm_calls"] += 1
                else:
                    i = rng.choices(range(len(typed)), weights=ws)[0]
            a, b, c = typed.pop(i)
            chosen.append((a, b, c, who))
            if memory is not None and retrieval and arm == "full":
                memory.retrieve(c.parts, k=5, round_=round_, proposer=who)
                rec["retrieved"] += 1
        new = []
        for a, b, c, who in chosen:
            if c is None or c.parts in seen:
                continue
            seen.add(c.parts)
            made_by[c.parts] = (a, b)
            new.append(c)
            if not c.closed:
                continue
            if sel is not None:
                rec["proposers"][who]["turns"] += 1
            if memory is not None and memory.decided(c.parts):
                rec["repeats"] += 1
            r = check5(c)
            rec["checks"] += 1
            rec["checked_seqs"].append(" ".join(c.parts))
            fired, ok, why = 0.0, None, ""
            if r.outcome == "accepted":
                ok, why = refute5(c, r, best)
                if ok:
                    fired = eta * (known_boost if r.measurement.get("known") else 1.0)
                    rec["survivors"].setdefault(r.statement, dict(node=r.node, generation=g, parts=list(c.parts)))
                    rec["first"].setdefault(r.node, g)
                    v = r.measurement.get("range", "")
                    if v.startswith("beta_W < "):
                        best[r.node] = max(best.get(r.node, Fraction(0)), Fraction(v.split("< ")[1].split()[0]))
                    if sel is not None:
                        rec["proposers"][who]["survivors"] += 1
                        sel.reward(PROPOSERS.index(who))
                else:
                    fired = -eta / 2
                    rec["refuted"].append(dict(child=c.id, statement=r.statement, reason=why))
            elif r.outcome == "rejected":
                fired = -eta / 2
            if memory is not None:
                memory.record(c.parts, c.problem, r.outcome, r.node, r.statement, why or r.statement, ok,
                              w.get(key(a, b), 1.0), round_, arm, who)
                if r.outcome == "stopped":
                    memory.block(c.problem, r.node, r.statement[:300], " ".join(c.parts))
            if boosted and fired:
                w[key(a, b)] = max(0.05, w.get(key(a, b), 1.0) + fired)
                if fired > 0:
                    frontier, k = [a.parts, b.parts], 1
                    while frontier and k <= 4:
                        nxt = []
                        for parts in frontier:
                            if parts in made_by:
                                pa, pb = made_by[parts]
                                w[key(pa, pb)] = w.get(key(pa, pb), 1.0) + eta * gamma ** k
                                nxt += [pa.parts, pb.parts]
                        frontier, k = nxt, k + 1
        pool += new
        if boosted:
            outs: Dict[str, List[str]] = {}
            for kk in w:
                outs.setdefault(kk.split("|")[0], []).append(kk)
            for ks in outs.values():
                mean = sum(w[x] for x in ks) / len(ks)
                for x in ks:
                    w[x] /= mean
    rec["weights"] = w
    rec["best"] = {k: str(v) for k, v in best.items()}
    if memory is not None:
        memory.save_weights(w)
        memory.commit()
    return rec


