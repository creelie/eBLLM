"""Blow-ups against the Hodge obstructions: what blowing up moves, and what it does not.

Uploaded by a second agent on Tubai's command.  Two blow-ups are computed here, both exactly.

1. Blowing up the variety.  For X smooth projective and Z a smooth closed subvariety of
   codimension c, the blow-up X~ = Bl_Z X has (Voisin, Hodge Theory and Complex Algebraic
   Geometry I, Theorem 7.31)

       H^k(X~, Q) = H^k(X, Q) (+) (+)_{i=1}^{c-1} H^{k-2i}(Z, Q)(-i),

   an isomorphism of Hodge structures, induced by pull-back and by the classes of the exceptional
   divisor.  So in every degree the Hodge classes of X~ are those of X and those of Z in lower
   degrees, and every Hodge class of X~ is algebraic exactly when the corresponding classes of X
   and Z are.  The defect of X~ (Hodge classes not known to be algebraic) is the defect of X plus
   the defects of Z in degrees k-i, i = 1, ..., c-1: a blow-up relocates an obstruction and never
   removes it.  That is the wall ``surgery-relocates`` of the atlas, here as a computation on Hodge
   numbers and defects (``blowup_hodge``, ``defect_transfer``).  When the centre is a point, a
   curve, a surface or an abelian threefold its Hodge classes are algebraic (Lefschetz (1,1) for
   divisors and the known cases in dimension at most three), so the defect of X~ equals that of X.

2. Blowing up the certified set.  Weil classes on an abelian 2n-fold of Weil type for the
   imaginary quadratic field K = Q(sqrt(-d)) carry a discriminant delta in Q^*/N(K^*).  The
   algebraicity of the Weil classes is multiplicative under products (Schoen 1998, Prop. 10; H8
   cor:prodalg): if it holds at discriminants delta and delta' it holds at delta delta'.  By the
   Hasse norm theorem for the cyclic extension K/Q, delta is a norm from K exactly when the
   Hilbert symbol (delta, -d)_v is 1 at every place v, so a class in Q^*/N(K^*) is the vector of
   its Hilbert symbols at the places dividing 2 d delta and at infinity, and the certified classes
   generate an F_2-subspace.  ``closure`` computes that subspace from a certified set, and
   ``blowup_discriminants`` says which candidate discriminants would follow from one more
   certificate.  With the only certified class being 1 (Markman, trivial discriminant) the closure
   is {1}: products buy nothing until a first nontrivial discriminant is certified, and then they
   buy the whole subgroup it generates.

Neither computation proves (F2).  The first shows that blowing up cannot break the wall; the
second measures exactly how far one new certificate would reach.
"""
from __future__ import annotations

from typing import Dict, Iterable, List, Sequence, Tuple


# ------------------------------------------------------------------- 1. blowing up the variety
def blowup_hodge(hX: Dict[Tuple[int, int], int], hZ: Dict[Tuple[int, int], int], c: int) -> Dict[Tuple[int, int], int]:
    """Hodge numbers of Bl_Z X from those of X and Z, Z of codimension c >= 2:
    h^{p,q}(X~) = h^{p,q}(X) + sum_{i=1}^{c-1} h^{p-i,q-i}(Z)."""
    if c < 2:
        raise ValueError("the centre must have codimension at least two")
    out = dict(hX)
    for (p, q), h in hZ.items():
        for i in range(1, c):
            out[(p + i, q + i)] = out.get((p + i, q + i), 0) + h
    return {k: v for k, v in out.items() if v}


def hodge_classes(h: Dict[Tuple[int, int], int], k: int) -> int:
    """Upper bound h^{k,k} for the dimension of the Hodge classes in degree 2k (equality for a
    very general member; the exact value needs the Hodge structure)."""
    return h.get((k, k), 0)


def defect_transfer(defX: Dict[int, int], defZ: Dict[int, int], c: int) -> Dict[int, int]:
    """Defects (Hodge classes of degree 2k not known algebraic) of Bl_Z X:
    def_k(X~) = def_k(X) + sum_{i=1}^{c-1} def_{k-i}(Z).  A blow-up adds the centre's obstructions
    and removes none."""
    out = dict(defX)
    for k, d in defZ.items():
        for i in range(1, c):
            out[k + i] = out.get(k + i, 0) + d
    return {k: v for k, v in out.items() if v}


def centre_is_harmless(dimZ: int, abelian: bool = False) -> bool:
    """True when every Hodge class of the centre is known algebraic: dimension at most two (Lefschetz
    (1,1)), or an abelian threefold (Hodge classes of abelian varieties of dimension at most three
    are generated by divisors)."""
    return dimZ <= 2 or (abelian and dimZ <= 3)


# ------------------------------------------------------------ 2. blowing up the certified set
def _vp(n: int, p: int) -> Tuple[int, int]:
    v = 0
    while n % p == 0:
        n //= p
        v += 1
    return v, n


def _legendre(a: int, p: int) -> int:
    a %= p
    if a == 0:
        return 0
    return 1 if pow(a, (p - 1) // 2, p) == 1 else -1


def hilbert_symbol(a: int, b: int, p) -> int:
    """(a, b)_p for nonzero integers and p a prime or the string 'inf' (Serre, A Course in
    Arithmetic, III.1.2)."""
    if a == 0 or b == 0:
        raise ValueError("nonzero arguments")
    if p == "inf":
        return -1 if (a < 0 and b < 0) else 1
    al, u = _vp(a, p)
    be, v = _vp(b, p)
    if p != 2:
        s = (-1) ** (al * be * (p - 1) // 2)
        return s * _legendre(u, p) ** be * _legendre(v, p) ** al
    eps = lambda x: ((x - 1) // 2) % 2          # x odd
    omg = lambda x: ((x * x - 1) // 8) % 2
    return (-1) ** (eps(u) * eps(v) + al * omg(v) + be * omg(u))


def _primes_dividing(n: int) -> List[int]:
    n = abs(n)
    out = []
    p = 2
    while p * p <= n:
        if n % p == 0:
            out.append(p)
            while n % p == 0:
                n //= p
        p += 1
    if n > 1:
        out.append(n)
    return out


def places(d: int, deltas: Iterable[int]) -> List:
    """The places at which (delta, -d)_v can differ from 1 for the given discriminants."""
    ps = set(_primes_dividing(2 * d))
    for x in deltas:
        ps.update(_primes_dividing(x))
    return sorted(ps) + ["inf"]


def norm_vector(delta: int, d: int, plc: Sequence) -> Tuple[int, ...]:
    """The class of delta in Q^*/N(K^*), K = Q(sqrt(-d)): one bit per place, 1 where the symbol is -1."""
    return tuple(1 if hilbert_symbol(delta, -d, v) == -1 else 0 for v in plc)


def is_norm(delta: int, d: int) -> bool:
    """Hasse: delta is a norm from Q(sqrt(-d)) exactly when every local symbol is 1."""
    return not any(norm_vector(delta, d, places(d, [delta])))


def closure(certified: Iterable[int], d: int, plc: Sequence) -> List[Tuple[int, ...]]:
    """The F_2-span of the classes of the certified discriminants: every product of them."""
    basis: List[Tuple[int, ...]] = []
    for x in certified:
        v = list(norm_vector(x, d, plc))
        for b in basis:                      # reduce against the echelon basis
            piv = next(i for i, t in enumerate(b) if t)
            if v[piv]:
                v = [s ^ t for s, t in zip(v, b)]
        if any(v):
            basis.append(tuple(v))
            basis.sort(key=lambda b: next(i for i, t in enumerate(b) if t))
    span = {tuple([0] * len(plc))}
    for b in basis:
        span |= {tuple(s ^ t for s, t in zip(x, b)) for x in span}
    return sorted(span)


def blowup_discriminants(d: int, certified: Sequence[int], candidates: Sequence[int]) -> Dict:
    """Which candidate discriminants follow by products from the certified ones, for K = Q(sqrt(-d))."""
    plc = places(d, list(certified) + list(candidates))
    span = set(closure(certified, d, plc))
    rows = []
    for x in candidates:
        v = norm_vector(x, d, plc)
        rows.append(dict(delta=x, is_norm=not any(v), follows=v in span, vector=v))
    return dict(d=d, places=plc, certified=list(certified), span_size=len(span),
                follow=[r["delta"] for r in rows if r["follows"]],
                open=[r["delta"] for r in rows if not r["follows"]], rows=rows)


def one_more(d: int, certified: Sequence[int], new: int, candidates: Sequence[int]) -> Dict:
    """What certifying one more discriminant would buy: the candidates that follow after it and not before."""
    before = set(blowup_discriminants(d, certified, candidates)["follow"])
    after = set(blowup_discriminants(d, list(certified) + [new], candidates)["follow"])
    return dict(new=new, gained=sorted(after - before), still_open=sorted(set(candidates) - after))


